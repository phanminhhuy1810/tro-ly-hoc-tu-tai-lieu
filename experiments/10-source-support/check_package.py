"""Refresh the local handoff manifest and check only known private values.

Does not claim to detect arbitrary unknown credentials. Runtime is excluded;
the original academic source and frozen evaluation split hashes must match.
"""
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import re
from urllib.parse import unquote, urlsplit

ROOT=Path(__file__).resolve().parents[2]
OUTPUT=ROOT/'backend/evidence/project-cleanup-package-check.json'
MANIFEST=ROOT/'MANIFEST.json'
SKIP={'.git','.venv','node_modules','__pycache__','.pytest_cache','.cache','.archive'}

def public_files():
    return sorted(p for p in ROOT.rglob('*') if p.is_file() and not p.is_symlink()
        and p!=MANIFEST and not set(p.relative_to(ROOT).parts)&SKIP
        and not p.is_relative_to(ROOT/'backend/runtime')
        and p.name!='.DS_Store' and not p.name.startswith('.env'))

private_names={'apikey','key','token','authtoken','password','secret','accesstoken','authorization','studysession','cookie','sessioncookie'}
values=set();private_count=0;wrong_modes=[]
def private_values(value):
    if isinstance(value,dict):
        for k,v in value.items():
            if re.sub('[^a-z]','',k.casefold()) in private_names and isinstance(v,str) and len(v)>10:
                values.add(v.encode())
            private_values(v)
    elif isinstance(value,list):
        for v in value:private_values(v)

for p in (ROOT/'backend/runtime').rglob('*.json'):
    try:value=json.loads(p.read_text())
    except (ValueError,UnicodeError,OSError):continue
    before=len(values);private_values(value)
    if len(values)>before or any(re.sub('[^a-z]','',k.casefold()) in private_names for k in value if isinstance(value,dict)):
        private_count+=1
        if p.stat().st_mode&0o777!=0o600:p.chmod(0o600)
        if p.stat().st_mode&0o777!=0o600:wrong_modes.append(str(p.relative_to(ROOT)))
for k,v in os.environ.items():
    if any(k.endswith(suffix) for suffix in ('API_KEY','ACCESS_TOKEN','AUTH_TOKEN','PASSWORD','SECRET')) and len(v)>10:values.add(v.encode())

files=public_files();secret_hits=[];missing=[];link_count=0
for p in files:
    data=p.read_bytes()
    if any(secret in data for secret in values):secret_hits.append(str(p.relative_to(ROOT)))
    if p.suffix.casefold()!='.md':continue
    text=re.sub(r'```.*?```','',data.decode('utf-8',errors='replace'),flags=re.S)
    text=re.sub(r'`[^`]*`','',text)
    for match in re.finditer(r'(?<!!)\[[^\]\n]+\]\(([^)]+)\)',text):
        target=match[1].strip().strip('<>')
        if not target or target.startswith('#') or urlsplit(target).scheme:continue
        link_count+=1
        target=unquote(target.split('#',1)[0].split('?',1)[0]);target=re.sub(r':\d+$','',target)
        if not (p.parent/target).exists():missing.append({'file':str(p.relative_to(ROOT)),'target':target})
academic=hashlib.sha256((ROOT/'sources/2026_Project_Virtual_Assistant_Academic.docx').read_bytes()).hexdigest()
assert academic=='10477b780feb504d649ad458cc381ed05eca4f47bc162ea4a8fb6eeb70c3a66e'
frozen={}
for name,expected in [('dev','e995b36a9de2802328b7ffd8d93e27aef3c6f4dfb0c7ca68f0291dc6bdb04b21'),
                      ('final','b9217a5a2ec433b3f449ad470ff473a13a092aede141562105234b0d81997d98')]:
    actual=hashlib.sha256((ROOT/'experiments/08-quality-evaluation'/(name+'.json')).read_bytes()).hexdigest()
    assert actual==expected;frozen[name]=actual
report={'purpose':'Known-secret, relative-link and hash/package check; not model quality, independent review, or arbitrary-secret detection.',
        'at':datetime.now(timezone.utc).isoformat(),'private_json_files_checked':private_count,'wrong_private_modes':wrong_modes,
        'known_private_value_matches':secret_hits,'relative_markdown_links_checked':link_count,'missing_relative_markdown_targets':missing,
        'academic_source_sha256':academic,'frozen_evaluation_sha256':frozen,'external_zip_updated':False,
        'passed':not(wrong_modes or secret_hits or missing)}
OUTPUT.write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')
if not report['passed']:
    print(json.dumps({'passed':False,'matched_file_count':len(secret_hits),'wrong_mode_count':len(wrong_modes),'missing_links':missing},ensure_ascii=False))
    raise SystemExit('Package not ready; no secret values printed.')
prior=json.loads(MANIFEST.read_text())
prior.update(updated_date=datetime.now(timezone.utc).date().isoformat(),kind='consolidated_backend_frontend_review_not_accepted_release',
             exclusion='Manifest excludes itself, OS/cache files, environment secrets, installed runtimes and backend/runtime. No external review ZIP generated by this check.',
             files=[{'path':str(p.relative_to(ROOT)),'bytes':p.stat().st_size,'sha256':hashlib.sha256(p.read_bytes()).hexdigest()} for p in public_files()])
MANIFEST.write_text(json.dumps(prior,ensure_ascii=False,indent=2)+'\n')
print(json.dumps({'passed':True,'files':len(prior['files']),'private_json_files_checked':private_count,'markdown_links':link_count,'known_secret_matches':0}))
